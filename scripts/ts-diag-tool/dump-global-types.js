// Writes src/lib_global_types.rs: every global type name tsc knows with the same options
// compare.js uses (--strict, target ES2020, the default libs, which include the DOM).
//
// Problem: tsox has no lib declarations yet, so a reference to `Date`, `Map` or
// `HTMLElement` looks exactly like a reference to a name that does not exist. The check
// that reports TS2304 for an unknown type name would flag all of them, and the old
// hand-written list of "names lib.d.ts provides" covered a few dozen of the ~1,000.
// Picked: ask tsc. The list is generated from the same compiler the comparison runs, so
// it cannot drift from it, and `node dump-global-types.js` regenerates it after a
// TypeScript upgrade.
// Cost: a name on this list is treated as "a lib type tsox does not model", which is
// right for the false-error question and says nothing about what the type contains.
//
// Usage: node dump-global-types.js            (from scripts/ts-diag-tool)
const fs = require("fs");
const os = require("os");
const path = require("path");
const ts = require("typescript");

const dir = fs.mkdtempSync(path.join(os.tmpdir(), "global-types-"));
const probe = path.join(dir, "probe.ts");
fs.writeFileSync(probe, "export {};\n");

const program = ts.createProgram([probe], {
  strict: true,
  noEmit: true,
  skipLibCheck: true,
  target: ts.ScriptTarget.ES2020,
  module: ts.ModuleKind.CommonJS,
});
const checker = program.getTypeChecker();
const source = program.getSourceFile(probe);

// Type-meaning symbols in scope at the top of a module are the globals a type reference
// can name. `export {}` makes the probe a module, so nothing of its own is in scope.
const names = new Set(
  checker
    .getSymbolsInScope(source, ts.SymbolFlags.Type)
    .map((symbol) => symbol.getName())
    // Compiler-internal names (`__type`, `__object`) and the `default` export are not
    // names a program can write as a type reference.
    .filter((name) => /^[A-Za-z_$][\w$]*$/.test(name) && !name.startsWith("__")),
);
const sorted = [...names].sort();

const out = `// Generated by scripts/ts-diag-tool/dump-global-types.js from TypeScript ${ts.version}
// (--strict, target ES2020, default libs). Do not edit by hand: rerun the script.

// Every global type name tsc knows with those options, sorted so lookups can binary-search.
static LIB_GLOBAL_TYPES: &[&str] = &[
${sorted.map((n) => `    "${n}",`).join("\n")}
];

// True when \`name\` is a type the standard library provides without any declaration in
// the file. tsox does not model these yet, so a reference to one is an unsupported
// type, not a missing name.
pub fn is_lib_global_type(name: &str) -> bool {
    LIB_GLOBAL_TYPES.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_list_is_sorted_and_free_of_duplicates() {
        assert!(LIB_GLOBAL_TYPES.windows(2).all(|pair| pair[0] < pair[1]));
    }

    #[test]
    fn common_library_types_are_known() {
        for name in ["Array", "Date", "Map", "Promise", "Record", "HTMLElement", "Error"] {
            assert!(is_lib_global_type(name), "{name}");
        }
    }

    #[test]
    fn a_made_up_name_is_not_known() {
        assert!(!is_lib_global_type("Missing"));
    }
}
`;
const target = path.join(__dirname, "..", "..", "src", "lib_global_types.rs");
fs.writeFileSync(target, out);
console.log(`wrote ${sorted.length} names to ${path.relative(process.cwd(), target)}`);
